def valid_question(q):
    """Shape check shared by the live-AI path and the pre-generated pool."""
    if not isinstance(q, dict):
        return False
    if q.get("category") not in config.CATEGORIES:
        return False
    if q.get("type") not in ("mc", "short"):
        return False
    if not q.get("question") or not q.get("answer"):
        return False
    if q["type"] == "mc" and len(q.get("options") or []) != 4:
        return False
    return True


def question_id(q):
    """Stable id derived from a question's text AND its passage.

    Same scheme for bank AND AI questions, so a verbatim repeat hashes to the
    same id and is recognized as already-seen. The passage is included so two
    reading questions that share a generic stem ("What is the main idea of this
    passage?") but have different passages get DIFFERENT ids — otherwise acing
    one would wrongly retire all of them. Questions without a passage keep the
    old text-only id, so existing mastery data stays valid."""
    basis = (q.get("question") or "").strip()
    passage = q.get("passage")
    if passage:
        basis += "\n" + str(passage).strip()
    return hashlib.sha1(basis.encode("utf-8")).hexdigest()[:10]


_OPT_PREFIX = re.compile(r"^\s*[A-Da-d][.):]\s+")


def ensure_option_letters(q):
    """Guarantee MC options read 'A. ...', 'B. ...' by position.

    The AI sometimes returns bare options with no letters, leaving the kid
    nothing to map their a/b/c/d answer to. Idempotent — strips any existing
    prefix first, so re-labeling never doubles up."""
    if q.get("type") == "mc" and q.get("options"):
        letters = "ABCD"
        q["options"] = [
            f"{letters[i]}. {_OPT_PREFIX.sub('', str(opt)).strip()}"
            for i, opt in enumerate(q["options"][:4])
        ]
    return q


# Give every bank question a stable id so progress can be tracked across sessions.
for _q in BANK:
    _q["id"] = question_id(_q)


def _order(pool, review):
    """Questions due for review (missed in a past session) come first, then
    fresh ones — each group shuffled so sessions still feel varied."""
    due = [q for q in pool if q["id"] in review]
    fresh = [q for q in pool if q["id"] not in review]
    random.shuffle(due)
    random.shuffle(fresh)
    return due + fresh


